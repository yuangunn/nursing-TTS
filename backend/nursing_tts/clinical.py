"""Ward clinical knowledge base: which diagnoses, complaints, drains, diets, education points and
discharge details go with each surgery or chemotherapy regimen.

Scenario families are the surgeries and regimens this ward actually sees (GS/OBGY/URO/ENT/OS/PS +
breast/colon/gyn chemo).  Every entry only lists combinations that are clinically plausible; the
random patient/form generator (fake.py) draws from these so a virtual chart hangs together.

``form`` values override template fields by key (see templates/*.py option values):
list -> pick one (select) or a few (multi); None -> drop the field; scalar -> set.
``pools`` override free-text pools by field key ("s4.course" beats "course").
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class Scenario:
    key: str                      # chart name as the ward writes it
    ko: str                       # Korean name
    abbr: str                     # how it is said in handover
    dept: str
    dx: tuple[str, ...]
    cc: tuple[str, ...]
    pi: tuple[str, ...]
    age: tuple[int, int] = (30, 80)
    sex: str | None = None
    kind: str = "op"              # op | chemo
    los: tuple[int, int] = (2, 5)  # typical discharge POD (op) / admission days (chemo)
    form: dict[str, Any] = field(default_factory=dict)
    pools: dict[str, tuple[str, ...]] = field(default_factory=dict)


